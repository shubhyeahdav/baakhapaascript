"""Write down what the video parser thinks each kind of line is.

The editor and the backend parser must agree about what a line IS. They are
written in different languages, by different people, months apart, and nothing
connects them — so the only thing stopping them drifting is a test that reads
one and checks the other.

A line the editor treats as a cue but the parser reads as narration corrupts
every runtime estimate in the format, silently: the cue is not spoken, so the
word count is wrong, so the section's duration is wrong, so the retention shape
is drawn against a runtime nobody has. That failure has no symptom until a
writer notices their twelve-minute video is reported as nine.

This writes the Python side's verdicts to a fixture the JS test asserts
against. Run it after ANY change to `videoscript.parse`, and commit the diff:
a change to the fixture is a deliberate change to the contract, and should be
reviewed as one.

    ./venv/Scripts/python export_parser_contract.py
"""
import json
from pathlib import Path

import videoscript

# Lines chosen for the places the two implementations could plausibly diverge,
# not for coverage of the happy path. Every one of these was a real decision in
# one parser or the other.
CASES = [
    # Headings, with and without a target, numbered and not.
    "## HOOK - 0:15",
    "## OBJECTIVE",
    "## SEGMENT 1 - 3:00",
    "## PROOF - 1:30",
    "## HOOK — 0:15",          # em dash, which a smart editor produces
    "##HOOK",                  # no space: NOT a heading in either
    "#  HOOK",                 # one hash: not a heading
    "  ## HOOK",               # leading whitespace is allowed

    # Cues. The label must be uppercase; the distinction between the two kinds
    # is whether it starts with ON SCREEN.
    "[B-ROLL: empty hall]",
    "[ON SCREEN: 72%]",
    "[ON SCREEN TEXT: 72%]",
    "[NOTE: anything uppercase is a cue]",
    "[b-roll: lowercase is not]",
    "[B-ROLL:no space after colon]",
    "[B-ROLL: ]",              # empty cue body
    "[not a cue at all]",

    # Narration, including the lines a SCREENPLAY parser would treat specially.
    # An all-caps line is a character cue on a screenplay page and is plain
    # narration here; if the JS side ever borrows the screenplay rule, this is
    # the case that catches it.
    "Nobody finishes a Nepali web series.",
    "SUNITA",
    "        indented like a dialogue block",
    "INT. CHIYA PASAL - DAY",
    "FADE IN:",
    "नेपाली मा नरेशन",
]

OUT = Path(__file__).resolve().parents[1] / "baakhapaa-frontend" / "src" / "utils" / "parser-contract.json"


def verdicts() -> dict:
    """One verdict per case. `dropped` means the parser kept no element for
    that line at all — blank lines, which carry no meaning in this format."""
    out = {}
    for line in CASES:
        elements = videoscript.parse(line)
        out[line] = elements[0].type if elements else "dropped"
    return out


if __name__ == "__main__":
    data = {
        "_comment": (
            "Generated by baakhapaa-backend/export_parser_contract.py. "
            "The JS parser is asserted against this. A change here is a "
            "deliberate change to the contract between the two parsers — "
            "review it as one."
        ),
        "verdicts": verdicts(),
    }
    OUT.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(data['verdicts'])} cases)")
